const fs = require('node:fs/promises');
const path = require('node:path');

const scriptDirectory = __dirname;
const projectRoot = path.resolve(scriptDirectory, '..');
const coveragePath = path.join(projectRoot, 'src', 'services', 'modules', 'cef3ApiCoverage.generated.json');
const nativeOutputPath = path.join(projectRoot, 'native', 'cef3-bridge', 'Cef3OperationCatalog.generated.inc');
const typeScriptOutputPath = path.join(projectRoot, 'src', 'services', 'modules', 'cef3SafeApiCatalog.generated.ts');
const checkOnly = process.argv.includes('--check');

const DOCUMENT_BY_MODULE = new Map([
  ['lingbuilder.cef3.browser', 'electron/docs/modules/cef3/browser.md'],
  ['lingbuilder.cef3.events', 'electron/docs/modules/cef3/events.md'],
  ['lingbuilder.cef3.session', 'electron/docs/modules/cef3/session.md'],
  ['lingbuilder.cef3.transfer', 'electron/docs/modules/cef3/transfer.md'],
  ['lingbuilder.cef3.objects', 'electron/docs/modules/cef3/objects.md'],
  ['lingbuilder.cef3.automation', 'electron/docs/modules/cef3/automation.md'],
  ['lingbuilder.cef3.network', 'electron/docs/modules/cef3/network.md'],
  ['lingbuilder.cef3.devtools', 'electron/docs/modules/cef3/devtools.md'],
  ['lingbuilder.cef3.views', 'electron/docs/modules/cef3/views.md'],
  ['lingbuilder.cef3.osr', 'electron/docs/modules/cef3/osr.md'],
  ['lingbuilder.cef3.platform', 'electron/docs/modules/cef3/platform.md']
]);

function operationId(signatureHash) {
  return BigInt(`0x${signatureHash.slice(0, 16)}`);
}

function escapeCpp(value) {
  return String(value ?? '')
    .replaceAll('\\', '\\\\')
    .replaceAll('"', '\\"')
    .replaceAll('\r', '\\r')
    .replaceAll('\n', '\\n');
}

function displayChineseName(entry) {
  return Array.isArray(entry.commandNames) && entry.commandNames.length > 0
    ? entry.commandNames[0]
    : entry.chineseName;
}

function renderNative(entries) {
  const rows = [...entries].sort((left, right) => {
    const leftId = operationId(left.signatureHash);
    const rightId = operationId(right.signatureHash);
    return leftId < rightId ? -1 : leftId > rightId ? 1 : 0;
  }).map(entry => {
    const codecs = entry.inputCodecs.join(',');
    return `  {UINT64_C(0x${entry.signatureHash.slice(0, 16)}), L"${escapeCpp(entry.functionId)}", L"${escapeCpp(entry.moduleId)}", L"${escapeCpp(displayChineseName(entry))}", L"${escapeCpp(entry.officialName)}", L"${escapeCpp(codecs)}", L"${escapeCpp(entry.outputCodec)}", L"${escapeCpp(entry.thread)}", L"${escapeCpp(entry.execution)}", L"${escapeCpp(entry.ownership)}", L"${escapeCpp(entry.implementationStatus)}", ${entry.publicSurface ? 'true' : 'false'}},`;
  });
  return [
    '// Generated by electron/scripts/generate-cef3-safe-api-catalog.cjs. Do not edit.',
    'static constexpr Cef3OperationDescriptorV4 kCef3OperationCatalogV4[] = {',
    ...rows,
    '};',
    '',
    'static constexpr size_t kCef3OperationCatalogV4Size =',
    '    sizeof(kCef3OperationCatalogV4) / sizeof(kCef3OperationCatalogV4[0]);',
    ''
  ].join('\n');
}

function renderTypeScript(entries, baseline) {
  const values = entries.map(entry => ({
    operationId: `0x${entry.signatureHash.slice(0, 16)}`,
    functionId: entry.functionId,
    signatureHash: entry.signatureHash,
    moduleId: entry.moduleId,
    chineseName: displayChineseName(entry),
    commandNames: Array.isArray(entry.commandNames) ? entry.commandNames : [],
    officialName: entry.officialName,
    officialSignature: entry.officialSignature,
    englishAliases: entry.englishAliases,
    inputCodecs: entry.inputCodecs,
    outputCodec: entry.outputCodec,
    responseSchema: entry.responseSchema,
    timeoutMs: entry.timeoutMs,
    defaultAction: entry.defaultAction,
    thread: entry.thread,
    execution: entry.execution,
    ownership: entry.ownership,
    implementationStatus: entry.implementationStatus,
    publicSurface: entry.publicSurface,
    classificationReason: entry.classificationReason,
    alternative: entry.alternative,
    wrapperSymbol: entry.wrapperSymbol,
    implementationLocator: entry.implementationLocator,
    testLocator: entry.testLocator,
    documentationLocator: DOCUMENT_BY_MODULE.get(entry.moduleId) || '',
    translationStatus: entry.translationStatus
  }));
  return [
    '// Generated by electron/scripts/generate-cef3-safe-api-catalog.cjs. Do not edit.',
    `export const CEF3_SAFE_API_BASELINE = ${JSON.stringify(baseline, null, 2)} as const;`,
    '',
    `export const CEF3_SAFE_API_CATALOG = ${JSON.stringify(values, null, 2)} as const;`,
    '',
    'export type Cef3SafeApiEntry = (typeof CEF3_SAFE_API_CATALOG)[number];',
    ''
  ].join('\n');
}

async function writeOrCheck(file, content) {
  if (!checkOnly) {
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, content, 'utf8');
    return;
  }
  const current = await fs.readFile(file, 'utf8').catch(() => '');
  if (current !== content) throw new Error(`CEF3 安全 API 目录已过期：${file}`);
}

async function main() {
  const coverage = JSON.parse(await fs.readFile(coveragePath, 'utf8'));
  if (coverage.schemaVersion !== 2 || !Array.isArray(coverage.signatures)) {
    throw new Error('CEF3 覆盖目录格式无效');
  }
  const seen = new Map();
  for (const entry of coverage.signatures) {
    const id = operationId(entry.signatureHash).toString();
    const previous = seen.get(id);
    if (previous) throw new Error(`CEF3 v4 操作 ID 冲突：${previous} / ${entry.functionId}`);
    seen.set(id, entry.functionId);
  }
  const entries = [...coverage.signatures].sort((left, right) => left.functionId.localeCompare(right.functionId));
  await writeOrCheck(nativeOutputPath, renderNative(entries));
  await writeOrCheck(typeScriptOutputPath, renderTypeScript(entries, coverage.baseline));
  console.log(`CEF3 安全 API 目录${checkOnly ? '已同步' : '已生成'}：${entries.length} 项`);
}

main().catch(error => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
